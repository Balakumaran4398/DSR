  private getDateRangeLabel(start: Date, end: Date): string {
    if (!start || !end) return '';
    const sameMonthYear = start.getMonth() === end.getMonth() && start.getFullYear() === end.getFullYear();

    if (sameMonthYear) {
      return `${start.getDate()}–${end.getDate()} ${start.toLocaleString('en-US', { month: 'long', year: 'numeric' })}`;
    }
    const startLabel = start.toLocaleDateString('en-US', { day: '2-digit', month: 'short', year: 'numeric' });
    const endLabel = end.toLocaleDateString('en-US', { day: '2-digit', month: 'short', year: 'numeric' });
    return `${startLabel} – ${endLabel}`;
  }

  private getInputDateRangeText(fromdate: any, todate: any): string {
    const fromDate = this.formatInputDateToYMD(fromdate);
    const toDate = this.formatInputDateToYMD(todate);

    if (fromDate && toDate) {
      return `${fromDate} to ${toDate}`;
    }

    return fromDate || toDate || '';
  }

  private formatInputDateToYMD(value: any): string {
    if (!value) {
      return '';
    }

    if (typeof value === 'string') {
      const trimmed = value.trim();
      const ymdMatch = /^(\d{4})-(\d{2})-(\d{2})/.exec(trimmed);
      if (ymdMatch) {
        return `${ymdMatch[1]}-${ymdMatch[2]}-${ymdMatch[3]}`;
      }
    }

    const date = new Date(value);
    if (Number.isNaN(date.getTime())) {
      return String(value);
    }

    return `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}-${String(
      date.getDate()
    ).padStart(2, '0')}`;
  }

  private formatDate(date: Date): string {
    const d = date.getDate().toString().padStart(2, '0');
    const m = (date.getMonth() + 1).toString().padStart(2, '0');
    const y = date.getFullYear();
    return `${d}-${m}-${y}`;
  }

  private getOverviewStatusKey(status: any): string {
    const normalized = String(status ?? '')
      .trim()
      .toLowerCase()
      .replace(/[_\s]+/g, '-');

    if (normalized === 'closed') return 'closed';
    if (normalized === 'in-progress' || normalized === 'inprogress') return 'in-progress';
    if (normalized === 'open') return 'open';
    if (normalized === 'completed' || normalized === 'complete') return 'completed';
    if (normalized === 'failed' || normalized === 'fail') return 'failed';
    return normalized;
  }

  private getReleaseStatusKey(status: any): string {
    const normalized = String(status ?? '')
      .trim()
      .toLowerCase()
      .replace(/[_\s]+/g, '-');

    if (normalized === 'open') return 'open';
    if (normalized === 'in-progress' || normalized === 'inprogress') return 'in-progress';
    if (normalized === 'to-be-tested' || normalized === 'tobe-tested' || normalized === 'to-be-test' || normalized === 'to-be-tested') return 'to-be-tested';
    if (normalized === 'in-review' || normalized === 'inreview') return 'in-review';
    if (normalized === 'completed' || normalized === 'complete') return 'completed';
    if (normalized === 'failed' || normalized === 'fail') return 'failed';
    return normalized;
  }

