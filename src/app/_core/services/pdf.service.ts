  private getReleaseOverdueDate(release: any): string {
    const overdueState = this.getReleaseOverdueState(release);
    const daysUntilRelease = this.getDaysUntilRelease(release?.released_date);

    if (overdueState === 'overdue') {
      return `${release?.released_date ?? ''}`.trim() || '-';
    }

    if (overdueState === 'high-warning') {
      return daysUntilRelease === 0 ? 'Due Today' : 'Due Tomorrow';
    }

    if (overdueState === 'warning') {
      return `Due in ${daysUntilRelease} days`;
    }

    return '-';
  }

  private getReleaseOverdueState(release: any): 'none' | 'warning' | 'high-warning' | 'overdue' {
    if (!this.isUpcomingRelease(release)) {
      return 'none';
    }

    const daysUntilRelease = this.getDaysUntilRelease(release?.released_date);

    if (daysUntilRelease === null) {
      return 'none';
    }

    if (daysUntilRelease < 0) {
      return 'overdue';
    }

    if (daysUntilRelease <= 1) {
      return 'high-warning';
    }

    return 'warning';
  }

