  private getReleasePerformance(release: any): string {
    if (this.isReleasePerformancePending(release)) {
      return 'Pending';
    }

    const plannedDate = this.parseReleaseDate(`${release?.planned_date ?? ''}`.trim());
    const releaseDate = this.parseReleaseDate(`${release?.released_date ?? ''}`.trim());

    if (!plannedDate || !releaseDate) {
      return '-';
    }

    plannedDate.setHours(0, 0, 0, 0);
    releaseDate.setHours(0, 0, 0, 0);

    if (releaseDate.getTime() < plannedDate.getTime()) {
      return 'Very Good';
    }

    if (releaseDate.getTime() === plannedDate.getTime()) {
      return 'Good';
    }

    return 'Poor';
  }

