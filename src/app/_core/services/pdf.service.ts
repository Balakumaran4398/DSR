  private drawTicketRemarks(doc: any, cell: any, remarks: any[]): void {
    const fontSize = 8;
    const lineHeight = 4.2;
    const leftPadding = 1.4;
    const topPadding = 2.2;
    const maxWidth = Math.max(cell.width - (leftPadding * 2), 10);
    let y = cell.y + topPadding + 2.8;

    doc.setFontSize(fontSize);
    doc.setTextColor(0, 0, 0);

    if (!Array.isArray(remarks) || !remarks.length) {
      doc.setFont(undefined, 'normal');
      doc.text('-', cell.x + leftPadding, y);
      return;
    }

    for (const remark of remarks) {
      const label = `${remark.label} : `;
      const labelWidth = doc.getTextWidth(label);
      const valueLines = this.wrapTicketRemarkValue(
        doc,
        remark.value,
        Math.max(maxWidth - labelWidth, 18),
        maxWidth
      );

      doc.setFont(undefined, 'bold');
      doc.text(label, cell.x + leftPadding, y);

      doc.setFont(undefined, 'normal');
      doc.text(valueLines[0] || '-', cell.x + leftPadding + labelWidth, y);

      for (const line of valueLines.slice(1)) {
        y += lineHeight;
        doc.text(line, cell.x + leftPadding, y);
      }

      y += lineHeight + 0.8;
    }

    doc.setFont(undefined, 'normal');
  }

  private getTicketRemarkCellHeight(doc: any, remarks: any[], cellWidth: number): number {
    const fontSize = 8;
    const lineHeight = 4.2;
    const verticalPadding = 4.4;
    const maxWidth = Math.max(cellWidth - 2.8, 10);

    if (!Array.isArray(remarks) || !remarks.length) {
      return 11;
    }

    doc.setFontSize(fontSize);

    const contentHeight = remarks.reduce((height: number, remark: any) => {
      const label = `${remark.label} : `;
      const labelWidth = doc.getTextWidth(label);
      const valueLines = this.wrapTicketRemarkValue(
        doc,
        remark.value,
        Math.max(maxWidth - labelWidth, 18),
        maxWidth
      );

      return height + (Math.max(valueLines.length, 1) * lineHeight) + 0.8;
    }, 0);

    return Math.max(11, contentHeight + verticalPadding);
  }

  private wrapTicketRemarkValue(doc: any, value: any, firstLineWidth: number, nextLineWidth: number): string[] {
    const text = this.cleanPdfText(value);
    if (text === '-') {
      return ['-'];
    }

    const words = text.split(/\s+/).filter(Boolean);
    const lines: string[] = [];
    let currentLine = '';
    let activeWidth = firstLineWidth;

    for (const word of words) {
      const candidate = currentLine ? `${currentLine} ${word}` : word;
      if (doc.getTextWidth(candidate) <= activeWidth) {
        currentLine = candidate;
        continue;
      }

      if (currentLine) {
        lines.push(currentLine);
      }

      if (doc.getTextWidth(word) > nextLineWidth) {
        const splitWordLines = doc.splitTextToSize(word, nextLineWidth);
        lines.push(...splitWordLines.slice(0, -1));
        currentLine = splitWordLines[splitWordLines.length - 1] || '';
      } else {
        currentLine = word;
      }

      activeWidth = nextLineWidth;
    }

    if (currentLine) {
      lines.push(currentLine);
    }

    return lines.length ? lines : ['-'];
  }

  private cleanPdfText(value: any): string {
    if (this.isEmptyPdfValue(value)) {
      return '-';
    }

    return String(value)
      .replace(/<[^>]*>/g, ' ')
      .replace(/\s+/g, ' ')
      .trim();
  }

  private isEmptyPdfValue(value: any): boolean {
    if (value === null || value === undefined) {
      return true;
    }

    const normalized = String(value).trim();
    return normalized === '' || normalized.toLowerCase() === 'null' || normalized.toLowerCase() === 'undefined';
  }

