  private getTicketStatusLabel(status: any): string {
    const map: any = {
      0: 'Open',
      1: 'In-Progress',
      2: 'To-be-Tested',
      3: 'Delayed',
      4: 'Closed',
      5: 'Cancelled',
      6: 'Approved',
      7: 'Completed',
      8: 'Rejected',
      9: 'Failed',
      10: 'Passed'
    };

    const numericStatus = Number(status);
    if (!Number.isNaN(numericStatus) && map[numericStatus]) {
      return map[numericStatus];
    }

    const rawStatus = String(status ?? '').trim();
    if (!rawStatus) {
      return '-';
    }

    const normalized = rawStatus.toLowerCase().replace(/[_\s]+/g, '-');
    const textMap: any = {
      'open': 'Open',
      'in-progress': 'In-Progress',
      'to-be-tested': 'To-be-Tested',
      'delayed': 'Delayed',
      'closed': 'Closed',
      'cancelled': 'Cancelled',
      'approved': 'Approved',
      'completed': 'Completed',
      'rejected': 'Rejected',
      'failed': 'Failed',
      'passed': 'Passed'
    };

    return textMap[normalized] || rawStatus;
  }
