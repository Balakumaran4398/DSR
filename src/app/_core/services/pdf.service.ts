  private buildOverallTicketReportRows(rawData: any[], fromdate: any, todate: any): any[] {
    const source = Array.isArray(rawData) ? rawData : rawData ? [rawData] : [];
    const grouped: any = {};

    for (const ticket of source) {
      const dateKey = this.getTicketWorkDateKey(this.getOverallTicketDateValue(ticket));
      if (!dateKey) {
        continue;
      }

      if (!grouped[dateKey]) {
        grouped[dateKey] = [];
      }

      grouped[dateKey].push(this.mapOverallTicketReportRow(ticket));
    }

    const dateKeys = this.getTicketWorkReportDateKeys(fromdate, todate, Object.keys(grouped));
    const rows: any[] = [];

    for (const dateKey of dateKeys) {
      const day = this.getTicketWorkDayLabel(dateKey);
      const dateRows = grouped[dateKey] || [];

      if (!dateRows.length) {
        rows.push(this.createOverallTicketPlaceholderRow(dateKey, day));
        continue;
      }

      for (const row of dateRows) {
        rows.push({
          ...row,
          date: this.getTicketDateLabel(dateKey),
          day,
          _isSundayRow: day === 'SUN'
        });
      }
    }

    return rows.map((row: any, index: number) => ({
      ...row,
      sno: index + 1
    }));
  }

