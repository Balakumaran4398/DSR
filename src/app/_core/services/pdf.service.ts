  private getReleasePerformanceState(release: any): ReleasePerformanceState {
    const releaseDate = this.parseReleaseDate(this.getFirstDateValue(release, [
      'released_date',
      'release_date',
      'releaseDate',
      'scheduled_release_date',
      'scheduledReleaseDate'
    ]) || '');
    const completedDate = this.parseReleaseDate(this.getReleaseCompletionDate(release) || '');

    if (!releaseDate || !completedDate) {
      return 'none';
    }

    const plannedDate = this.parseReleaseDate(this.getFirstDateValue(release, [
      'planned_date',
      'plannedDate',
      'scheduled_date',
      'scheduledDate'
    ]) || '');
    const releaseTime = this.getStartOfDayTime(releaseDate);
    const completedTime = this.getStartOfDayTime(completedDate);
    const plannedTime = plannedDate ? this.getStartOfDayTime(plannedDate) : null;
    const daysBeforeRelease = Math.floor((releaseTime - completedTime) / 86400000);

    if (daysBeforeRelease >= 2) {
      return 'excellent';
    }

    if (daysBeforeRelease === 1) {
      return 'very-good';
    }

    if (daysBeforeRelease === 0) {
      return plannedTime === releaseTime ? 'excellent' : 'good';
    }

    return 'poor';
  }

